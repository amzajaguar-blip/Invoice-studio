#!/usr/bin/env python3
"""
Hardened patcher for android/app/build.gradle (generated by expo prebuild).

Fixes ALL known Play Console rejection causes for Milo Office:
  1. versionCode/versionName sync from app.json  (fixes "APK shadowed")
  2. useLegacyPackaging = FALSE                  (fixes 16 kB page-size rejection)
     `true` e' cio' che fece rifiutare v48/v49/v50/v52. Il valore non lo scrive
     piu' questo script: lo dichiara app.json via expo-build-properties e lo
     scrive `expo prebuild`. Qui resta solo l'assert finale.
  3. Release signing config injection
  4. Release buildType → signingConfigs.release
  5. debuggableVariants = []
  6. gradle.properties: solo le proprieta' grezze che app.json non copre —
     R8 full mode, uncompressed native libs, reactNativeArchitectures
  7. proguard-rules.pro copy

Idempotent: re-running yields the same output. Exits non-zero with full
diagnostic dump if any final-state assertion fails.

Environment variables consumed:
  ANDROID_KEYSTORE_PATH     – keystore path relative to android/app/
  ANDROID_KEYSTORE_PASSWORD – store password
  ANDROID_KEY_ALIAS         – key alias
  ANDROID_KEY_PASSWORD      – key password
"""
import json
import os
import re
import shutil
import sys

GRADLE_PATH   = os.path.join('android', 'app', 'build.gradle')
PROPS_PATH    = os.path.join('android', 'gradle.properties')
APP_JSON_PATH = 'app.json'
PROGUARD_SRC  = 'proguard-rules.pro'
PROGUARD_DST  = os.path.join('android', 'app', 'proguard-rules.pro')

FAILURES = []


def fail(msg):
    FAILURES.append(msg)
    print(f'❌ {msg}')


def ok(msg):
    print(f'✅ {msg}')


def warn(msg):
    print(f'⚠️  {msg}')


def info(msg):
    print(f'   {msg}')


# ── Read app.json (source of truth for version) ──────────────────────────────
target_vc = None
target_vn = None
if os.path.exists(APP_JSON_PATH):
    try:
        with open(APP_JSON_PATH) as f:
            cfg = json.load(f)['expo']
        target_vc = int(cfg['android']['versionCode'])
        target_vn = cfg['android'].get('versionName') or cfg.get('version') or ''
        ok(f'app.json source-of-truth: versionCode={target_vc} versionName="{target_vn}"')
    except Exception as e:
        fail(f'Could not parse app.json: {e}')
else:
    fail(f'app.json missing at {APP_JSON_PATH}')

# versionCode monotonicity guard: shadowed versions were 48/49/50.
if target_vc is not None and target_vc < 51:
    fail(f'versionCode {target_vc} < 51 — would be shadowed by v48/49/50 on Play Console')

# ── Read build.gradle ────────────────────────────────────────────────────────
if not os.path.exists(GRADLE_PATH):
    fail(f'{GRADLE_PATH} missing — did `expo prebuild` run?')
    print('Exiting early.')
    sys.exit(1)

gradle_path = GRADLE_PATH  # keep backward-compat var name below

with open(gradle_path, 'r') as f:
    content = f.read()

_before_vc = re.search(r'versionCode\s+(\d+)', content)
info(f'Current build.gradle versionCode: {_before_vc.group(1) if _before_vc else "?"}')

# ── FIX 1 ── Sync versionCode / versionName from app.json ────────────────────
# ROOT CAUSE of "APK shadowed by newer versionCode": `expo prebuild` hardcodes
# `versionCode 44` regardless of what's in app.json. We rewrite BOTH lines with
# values pulled from app.json, so the AAB emitted by `bundleRelease` declares
# the correct versionCode to Play Console.
content, n_vc = re.subn(r'versionCode\s+\d+',       f'versionCode {target_vc}', content)
content, n_vn = re.subn(r'versionName\s+"[^"]+"',  f'versionName "{target_vn}"', content)
ok(f'FIX 1 — versionCode/versionName synced (vc subs={n_vc}, vn subs={n_vn})')

release_block = '''
        release {
            def ksPath = System.getenv("ANDROID_KEYSTORE_PATH") ?: "debug.keystore"
            def ksPass = System.getenv("ANDROID_KEYSTORE_PASSWORD") ?: "android"
            def kAlias = System.getenv("ANDROID_KEY_ALIAS") ?: "invoicestudio"
            def kPass  = System.getenv("ANDROID_KEY_PASSWORD") ?: "android"
            storeFile file(ksPath)
            storePassword ksPass
            keyAlias kAlias
            keyPassword kPass
        }'''

# Insert release block after the closing brace of the debug signingConfig.
# Expo SDK 53 (RN 0.79) generates:
#   signingConfigs {
#       debug {
#           storeFile file('debug.keystore')
#           storePassword 'android'
#           keyAlias 'androiddebugkey'
#           keyPassword 'android'
#       }
#   }
# We insert the release block right after the debug block's closing brace.
# Use a simpler approach: replace the entire signingConfigs block.
old_signing_configs = '''    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }'''
new_signing_configs = '''    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        release {
            def ksPath = System.getenv("ANDROID_KEYSTORE_PATH") ?: "debug.keystore"
            def ksPass = System.getenv("ANDROID_KEYSTORE_PASSWORD") ?: "android"
            def kAlias = System.getenv("ANDROID_KEY_ALIAS") ?: "invoicestudio"
            def kPass  = System.getenv("ANDROID_KEY_PASSWORD") ?: "android"
            storeFile file(ksPath)
            storePassword ksPass
            keyAlias kAlias
            keyPassword kPass
        }
    }'''
content = content.replace(old_signing_configs, new_signing_configs)

# Switch release buildType to use release signingConfig.
# CRITICAL: only patch inside the `release { }` block, NOT the `debug { }` block.
# Expo 53 generates both:
#   debug   { signingConfig signingConfigs.debug }
#   release { signingConfig signingConfigs.debug }
# A global replace would change debug's signing config to .release, which then
# tries to read key alias 'invoicestudio' from Expo's default debug.keystore
# (which only has 'androiddebugkey'). DOTALL lets the pattern span lines.
content = re.sub(
    r"(release\s*\{[^}]*?signingConfig\s+signingConfigs\.)debug",
    r"\1release",
    content,
    flags=re.DOTALL
)

# ── Force JS bundle to be embedded in debug builds ───────────────────────────
# By default the React Native Gradle plugin treats "debug" as a debuggable
# variant and skips createBundleDebugJsAndAssets, so the APK has no
# index.android.bundle and shows a white screen when Metro is unavailable.
if not re.search(r'(?m)^(?!\s*//).*debuggableVariants\s*=', content):
    content = re.sub(
        r'(autolinkLibrariesWithApp\(\)\n)(\})',
        r'\1    // Standalone debug APK: embed the JS bundle instead of relying on Metro\n    debuggableVariants = []\n\2',
        content
    )
    print('✅ build.gradle patched: debuggableVariants = [] (bundle JS in debug)')
else:
    print('ℹ️  debuggableVariants already set, skipping')

# ── 16 KB page alignment for native libraries ──────────────────────────────
# Play Console requires .so libraries to be aligned to 16 KB page size for
# Android 15+ compatibility. Without this, the AAB is rejected.
#
# ATTENZIONE — useLegacyPackaging deve valere FALSE.
# `true` era la vecchia ipotesi, e le release v48/v49/v50/v52 sono state
# rifiutate da Play Console proprio perche' la spedivano. La checklist 16 KB
# (Ago 2025+) richiede le .so NON compresse nell'.aab, cosi' che il page loader
# possa mapparle allineate a 16 KB sui device con kernel a pagina da 16 KB
# (Pixel 8+, Pixel 9, S24). Chi legge solo l'intestazione di questo file e
# "corregge" il valore riapre un rifiuto gia' pagato.
#
# Questo script NON scrive piu' quel valore. Il build.gradle generato da
# prebuild contiene gia':
#     useLegacyPackaging (findProperty('expo.useLegacyPackaging')?.toBoolean() ?: false)
# cioe' legge la proprieta'. Sostituirla con un letterale, come si faceva qui,
# rendeva decorativo il valore in gradle.properties: si potevano avere le due
# fonti in disaccordo senza che nulla lo segnalasse. Ora la proprieta' la
# dichiara app.json (expo-build-properties) e la scrive prebuild; qui resta solo
# la verifica, in fondo al file.

with open(gradle_path, 'w') as f:
    f.write(content)

print('✅ build.gradle patched for release signing')


# ── gradle.properties: idempotent R8 / ProGuard / 16 KB enforcement ─────────
# Removes ALL existing occurrences of each required key, then injects
# exactly ONE line with the correct value. Eliminates duplicate-key ambiguity
# (Gradle's findProperty behavior with multiple occurrences is non-deterministic).
props_path = PROPS_PATH
if os.path.exists(props_path):
    with open(props_path, 'r') as f:
        props = f.read()

    # Solo le proprieta' che app.json NON sa esprimere.
    #
    # `android.enableProguardInReleaseBuilds`,
    # `android.enableShrinkResourcesInReleaseBuilds` ed `expo.useLegacyPackaging`
    # sono uscite da qui: le dichiara il plugin expo-build-properties in
    # app.json, e le scrive `expo prebuild` stesso. Tenerle anche qui creava due
    # fonti di verita' per lo stesso valore — ed e' cosi' che il workflow
    # arrivava ad appendere `enableR8.fullMode=false` subito dopo che questo
    # script aveva verificato `true`, lasciando in gradle.properties proprio la
    # chiave doppia che il commento qui sopra dichiara non deterministica.
    #
    # `android.enableR8.fullMode` resta: e' una proprieta' grezza di AGP, il
    # plugin non la copre. Vale `true` — full mode invece di compatibility mode
    # — perche' e' quanto richiesto da Play Console (avviso "R8 in modalita'
    # compatibilita'"). proguard-rules.pro tiene gia' pacchetti interi
    # (com.revenuecat.**, com.google.firebase.**, com.google.mlkit.**,
    # androidx.**, ecc.) apposta per assorbire l'ottimizzazione piu' aggressiva
    # di full mode senza rompere le chiamate a riflessione di quelle librerie.
    REQUIRED = {
        'android.enableR8.fullMode':                    'true',
        'android.bundle.enableUncompressedNativeLibs':  'true',
        'reactNativeArchitectures':                     'armeabi-v7a,arm64-v8a,x86,x86_64',
    }
    for key, val in REQUIRED.items():
        before = len(re.findall(rf'^{re.escape(key)}\s*=', props, re.MULTILINE))
        props = re.sub(rf'^{re.escape(key)}\s*=.*$', '', props, flags=re.MULTILINE)
        props += f'\n{key}={val}\n'
        info(f'  {key}: deduped ({before} → 1, value={val})')

    with open(props_path, 'w') as f:
        f.write(props)
    ok('gradle.properties rewritten (single-occurrence per required key)')
else:
    fail(f'⚠️  {props_path} missing')

# ── Copy proguard-rules.pro into android/app/ ───────────────────────────────
proguard_src = PROGUARD_SRC
proguard_dst = PROGUARD_DST
if os.path.exists(proguard_src):
    shutil.copy(proguard_src, proguard_dst)
    print(f'✅ proguard-rules.pro copied into {proguard_dst}')
else:
    fail(f'⚠️  proguard-rules.pro not found at {proguard_src}')

# ── FINAL STATE ASSERTIONS ──────────────────────────────────────────────────
# Read back files and verify every Play Console requirement is met. Fail loud.
print('\n── FINAL STATE ASSERTIONS ──────────────────────────────────')
with open(GRADLE_PATH) as f:
    final_gradle = f.read()
with open(PROPS_PATH) as f:
    final_props = f.read()

m_vc = re.search(r'versionCode\s+(\d+)', final_gradle)
m_vn = re.search(r'versionName\s+"([^"]+)"', final_gradle)


def count(key, text):
    return len(re.findall(rf'^{re.escape(key)}\s*=', text, re.MULTILINE))


checks = [
    ('build.gradle versionCode == app.json',
     m_vc and int(m_vc.group(1)) == target_vc,
     f'build.gradle={m_vc.group(1) if m_vc else "MISSING"} expected={target_vc}'),
    ('build.gradle versionName == app.json',
     m_vn and m_vn.group(1) == target_vn,
     f'build.gradle="{m_vn.group(1) if m_vn else "MISSING"}" expected="{target_vn}"'),
    # Si verifica che build.gradle *legga la proprieta'*, non che contenga un
    # letterale: e' la forma generata da prebuild, ed e' quella che tiene
    # allineate gradle.properties e la build. Un letterale qui sarebbe un
    # regresso, perche' scavalcherebbe in silenzio il valore dichiarato in
    # app.json.
    ('build.gradle useLegacyPackaging legge expo.useLegacyPackaging (16 KB readiness)',
     re.search(r'useLegacyPackaging\s*\(\s*findProperty\(\s*[\'"]expo\.useLegacyPackaging[\'"]',
               final_gradle) is not None,
     'build.gradle non legge la proprieta` expo.useLegacyPackaging '
     '(un letterale al suo posto scavalcherebbe app.json)'),
    ('release signingConfig present (with storeFile file(ksPath))',
     re.search(r'storeFile\s+file\(ksPath\)', final_gradle) is not None,
     '`storeFile file(ksPath)` not found — release signing config missing'),
    ('gradle.properties expo.useLegacyPackaging (count=1)',
     count('expo.useLegacyPackaging', final_props) == 1,
     f'count={count("expo.useLegacyPackaging", final_props)}, expected 1'),
    ('gradle.properties expo.useLegacyPackaging == false (16 KB readiness)',
     re.search(r'^expo\.useLegacyPackaging\s*=\s*false\s*$', final_props, re.MULTILINE) is not None,
     '`expo.useLegacyPackaging=false` not present in gradle.properties'),
    ('gradle.properties android.bundle.enableUncompressedNativeLibs == true',
     re.search(r'^android\.bundle\.enableUncompressedNativeLibs\s*=\s*true\s*$', final_props, re.MULTILINE) is not None,
     '`android.bundle.enableUncompressedNativeLibs=true` not present in gradle.properties'),
    ('gradle.properties reactNativeArchitectures includes arm64-v8a (16 KB ABI filter)',
     re.search(r'^reactNativeArchitectures\s*=.*arm64-v8a.*$', final_props, re.MULTILINE) is not None,
     '`reactNativeArchitectures` does not include arm64-v8a — Play Store compliance fails'),
    # Non basta contare le occorrenze: se il valore non viene verificato,
    # l'assert passa anche quando la build fa il contrario di quel che dice.
    # E' cosi' che il workflow poteva appendere `enableR8.fullMode=false` dopo
    # che questo script aveva scritto `true`, con tutte le spunte verdi.
    ('gradle.properties android.enableR8.fullMode == true (count=1)',
     count('android.enableR8.fullMode', final_props) == 1
     and re.search(r'^android\.enableR8\.fullMode\s*=\s*true\s*$', final_props, re.MULTILINE),
     f'count={count("android.enableR8.fullMode", final_props)}, atteso 1 con valore true'),
    # I due valori qui sotto li dichiara app.json (expo-build-properties) e li
    # scrive `expo prebuild`: questo assert e' una verifica vera, non la
    # rilettura di cio' che lo script ha appena scritto da se'.
    ('gradle.properties android.enableProguardInReleaseBuilds == true (count=1, da app.json)',
     count('android.enableProguardInReleaseBuilds', final_props) == 1
     and re.search(r'^android\.enableProguardInReleaseBuilds\s*=\s*true\s*$', final_props, re.MULTILINE),
     f'count={count("android.enableProguardInReleaseBuilds", final_props)}, atteso 1 con valore true'),
    ('gradle.properties android.enableShrinkResourcesInReleaseBuilds == true (count=1, da app.json)',
     count('android.enableShrinkResourcesInReleaseBuilds', final_props) == 1
     and re.search(r'^android\.enableShrinkResourcesInReleaseBuilds\s*=\s*true\s*$', final_props, re.MULTILINE),
     f'count={count("android.enableShrinkResourcesInReleaseBuilds", final_props)}, atteso 1 con valore true'),
    ('ANDROID_KEYSTORE_PATH env var present',
     bool(os.environ.get('ANDROID_KEYSTORE_PATH')),
     'env var missing — release will fall back to debug.keystore!'),
    ('ANDROID_KEY_ALIAS env var present',
     bool(os.environ.get('ANDROID_KEY_ALIAS')),
     'env var missing — fallback alias `invoicestudio` will be used'),
]

for label, passed, detail in checks:
    # `detail` e' il messaggio che spiega il FALLIMENTO: stamparlo anche accanto
    # a una spunta verde produceva righe come
    #   ✅ expo.useLegacyPackaging == false: `expo.useLegacyPackaging=false` not
    #      present in gradle.properties
    # cioe' un successo che si legge come un errore. In un log di CI lungo
    # centinaia di righe e' il modo piu' rapido per diagnosticare il problema
    # sbagliato.
    if passed:
        print(f'  ✅ {label}')
    else:
        print(f'  ❌ {label}: {detail}')
        FAILURES.append(f'{label}: {detail}')

if FAILURES:
    print(f'\n❌ patch_build_gradle.py FAILED — {len(FAILURES)} error(s):')
    for f in FAILURES:
        print(f'   • {f}')
    sys.exit(1)
else:
    print(f'\n✅ patch_build_gradle.py OK — v{target_vc} ({target_vn}) ready for Play Console.')
    sys.exit(0)
